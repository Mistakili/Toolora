export function getGlossaryEntry(slug: string): GlossaryEntry | undefined {
  return GLOSSARY.find((g) => g.slug === slug);
}

export function getAllGlossarySlugs(): string[] {
  return GLOSSARY.map((g) => g.slug);
}

